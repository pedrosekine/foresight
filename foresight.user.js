  const sleep = ms => new Promise(r => setTimeout(r, ms));
  const dayHeaders = () => [...document.querySelectorAll('[data-column-date]')]
    .map(h => ({ el: h, date: h.dataset.columnDate })).filter(h => h.date);
  const nowBlock = () => {
    const n = new Date();
    return Math.floor((n.getHours() * 60 + n.getMinutes()) / 30) * 30;
  };
  const slotStart = () => { const k = labelKey(gridSlot()); return k ? k.mins : null; };
  const isEvent = el => !!el && !!el.closest('[role="button"][aria-label]')
    && !(el.closest('[role="button"][aria-label]').id || '').startsWith('selectedInterval');

  function clickAt(x, y) {
    const el = document.elementFromPoint(x, y);
    // Never through an overlay, and never on an event: that opens it.
    if (!el || !surface()?.contains(el) || isEvent(el)) return false;
    const o = { bubbles: true, cancelable: true, button: 0, pointerId: 1, isPrimary: true,
                clientX: x, clientY: y };
    for (const t of ['pointerdown', 'mousedown', 'pointerup', 'mouseup', 'click']) {
      el.dispatchEvent(t.startsWith('pointer') ? new PointerEvent(t, o) : new MouseEvent(t, o));
    }
    return true;
  }

  // Select `date` at `mins` (minutes from midnight, a half-hour boundary).
  // Scrolls only when that half hour is off screen. null when there is no
  // day grid to click (month view, not rendered yet), false when the click
  // did not produce the slot, true when it did.
  async function placeSlot(date, mins) {
    const sc = q('.inDayScrollContainer');
    const head = dayHeaders().find(h => h.date === date);
    if (!sc || !head || sc.scrollHeight < 100) return null;
    const block = sc.scrollHeight / 48;
    const content = (mins / 1440) * sc.scrollHeight + block / 2;   // middle of the half hour
    if (content < sc.scrollTop + block || content > sc.scrollTop + sc.clientHeight - block) {
      sc.scrollTop = Math.max(0, content - sc.clientHeight / 2);
      sc.setAttribute('data-owa-scrolled', '');   // ours now: settleScroll must not undo it
    }
    const hr = head.el.getBoundingClientRect();
    const y = sc.getBoundingClientRect().top + content - sc.scrollTop;
    const landed = () => {
      const got = slotStart();
      return !!gridSlot() && (got === null || got === mins);   // null: label without a year (locale)
    };
    // Events can sit under the middle of a column; the left edge rarely.
    for (const x of [hr.left + hr.width / 2, hr.left + 6]) {
      if (!clickAt(x, y)) continue;
      for (let i = 0; i < 10 && !gridSlot(); i++) await sleep(100);   // one React render away
      if (landed()) return true;
      // Off by whole blocks: the geometry is slightly wrong, the label is not.
      const got = slotStart();
      if (gridSlot() && got !== null && (got - mins) % 30 === 0) {
        clickAt(x, y - ((got - mins) / 30) * block);
        for (let i = 0; i < 10 && !landed(); i++) await sleep(100);
        if (landed()) return true;
      }
    }
    return false;
  }

  // Serialises the two callers: the load-time placement must not race the
  // one that follows a navigation.
  let slotBusy = false, nextSlotTry = 0;

  // Focus that nobody chose: nothing, or a bare container. Outlook parks
  // focus on a div at load; that is not a place the user put it.
  const focusIdle = () => {
    const ae = document.activeElement;
    return !ae || ae === document.body
      || (ae.tagName === 'DIV' && !ae.getAttribute('role')
          && !ae.closest('#omarchy-owa-bar, #omarchy-owa-toggle, [role="dialog"]'));
  };

  // No slot and nothing deliberately focused: select the current half hour
  // on today, or the first day on screen when today is not. Runs from the
  // mutation loop, so it is rate-limited and waits for the grid to settle.
  function ensureSlot() {
    if (slotBusy || gridSlot() || overlayOpen() || !focusIdle()) return;
    const sc = q('.inDayScrollContainer');
    if (!sc || !sc.hasAttribute('data-owa-scrolled')) return;
    if (performance.now() < nextSlotTry) return;
    nextSlotTry = performance.now() + 2000;
    slotBusy = true;
    const date = targetDate() || localDate(), mins = nowBlock();
    placeSlot(date, mins)
      .then(ok => { if (ok === false) console.warn('[foresight] slot: could not select', date, fromMinutes(mins)); })
      .finally(() => { slotBusy = false; });
  }

  // Today / Next / Previous: run the navigation, wait for the week to
  // change, then put the slot back where it was relative to the new week —
  // same column, same time. Today goes to today at the current half hour.
  async function followSlot(nav, go) {
    const before = dayHeaders().map(h => h.date).join();
    const prev = labelKey(gridSlot());
    const idx = prev ? dayHeaders().findIndex(h => +h.date.slice(-2) === prev.day) : -1;
    slotBusy = true;
    try {
      go();
      // Today on the current week changes nothing, so do not wait 3s for it.
      for (let i = 0; i < 30 && dayHeaders().map(h => h.date).join() === before
                      && !(nav === 0 && i >= 3); i++) await sleep(100);
      const heads = dayHeaders();
      if (!heads.length) return;
      let date, mins;
      if (nav === 0) { date = localDate(); mins = nowBlock(); }
      else { date = (heads[idx] || heads[0]).date; mins = prev ? prev.mins : nowBlock(); }
      if (!heads.some(h => h.date === date)) date = heads[0].date;
      const ok = await placeSlot(date, mins);
      if (ok === false) console.warn('[foresight] slot: could not select', date, fromMinutes(mins));
    } finally { slotBusy = false; }
  }

  // Tab is a two-region switch: the calendar, or the bar. Everything else on
  // the page is out of the order entirely, so it is always obvious where the
  // next press goes.
  //
  // Inside the calendar it still reaches events, because opening one with
  // Enter and deleting it with Delete is worth keeping — but it goes to the
  // event nearest where you are rather than the first of the day, which is
  // what Outlook does and what makes it feel arbitrary when you have arrowed
  // to 15:00 and land on something at 08:00.
  //
  // Position cannot be used for any of this: the selected slot's rect is zero
  // wide and spans the entire day (w:0, h:1920), so it says nothing about
  // where you are. The aria-labels do — "17:30 to 18:00, Tuesday, August 25,
  // 2026" — and the numbers in them are the same in every locale even though
  // the words are not. Day headers carry a date but no year, so requiring a
  // year keeps them out without naming them.
  const labelKey = el => {
    const l = (el && el.getAttribute('aria-label')) || '';
    const date = /\b(\d{1,2}),\s*(\d{4})\b/.exec(l);
    if (!date) return null;
    const time = /(\d{1,2}):(\d{2})/.exec(l);
    return {
      day: +date[1],
      year: +date[2],
      mins: time ? (+time[1]) * 60 + (+time[2]) : 0,   // all-day sorts first
      x: Math.round(el.getBoundingClientRect().x),
    };
  };

  // Chronological order. Sorting on the day number rather than a parsed date
  // is deliberate: month names are translated, and within any one view a day
  // number appears once. It misorders across a month boundary in month view,
  // which is a smaller price than depending on locale.
  function calendarEvents() {
    const s = surface();
    if (!s) return [];
    return [...s.querySelectorAll('[role="button"][aria-label]')]
      .filter(isVisible)
      .filter(el => !(el.id || '').startsWith('selectedInterval'))
      .map(el => ({ el, key: labelKey(el) }))
      .filter(o => o.key)
      .sort((a, b) => a.key.day - b.key.day || a.key.mins - b.key.mins || a.key.x - b.key.x);
  }

  // Past events: over on a day before today, or ended before now on today.
  // The day comes from the column the event sits in, the end from the second
  // time in its label; an all-day event has no time and is past with its day.
  // Outlook's own "dim past events" recolours them, which the chip mapping
  // then normalises away, so the fade here is the only distinction — and
  // it is opacity, so the theme's colours survive it.
  let lastPastMark = 0;
  function markPast() {
    const now = performance.now();
    if (now - lastPastMark < 1000) return;
    lastPastMark = now;
    const heads = dayHeaders().map(h => ({ date: h.date, r: h.el.getBoundingClientRect() }));
    if (!heads.length) return;
    const today = localDate();
    const n = new Date(), nowMins = n.getHours() * 60 + n.getMinutes();
    for (const o of calendarEvents()) {
      const r = o.el.getBoundingClientRect(), cx = r.x + r.width / 2;
      const h = heads.find(h => cx >= h.r.left && cx <= h.r.right);
      if (!h) continue;
      const times = ((o.el.getAttribute('aria-label') || '').match(/\d{1,2}:\d{2}/g) || []);
      const end = times.length >= 2 ? toMinutes(times[1]) : (times.length ? toMinutes(times[0]) + 30 : 1440);
      const past = h.date < today || (h.date === today && end <= nowMins);
      o.el.toggleAttribute('data-owa-past', past);
    }
  }

  // The all-day strip shows as many rows as its height allows and folds the
  // rest into "+N". That height is Outlook's own state, set by dragging the
  // splitter at the strip's foot (measured 2026-09-17: a 2px row-resize
  // handle; 44px holds two 21px rows; the height survives week changes and
  // a reload). So the strip is sized by driving that splitter, to one row
  // more than the fullest day in view needs — an empty row to drop a new
  // all-day event into — capped by the setting, with Outlook's own floor
  // below. Once per week and need, so a drag by hand is not undone.
  const allDayArea = () => q('[data-app-section^="calendar-view-header"]');
  const allDayStrip = () => q('[data-allday-placeholder]');
  let lastFit = null, fitting = false, fitTries = 0, fitRetry = 0;

  // Rows the fullest day needs, and the row pitch, read off the chips'
  // inline positions: a chip at top 21px is on row 1; "+15" on row 1 stands
  // for 15 more, so that day needs 16.
  function allDayNeed(area) {
    let need = 0, pitch = 21;
    const tops = new Set();
    for (const w of area.querySelectorAll('[data-calitemid]')) {
      const box = w.closest('[style*="top"]') || w;
      const top = parseFloat(box.style.top) || 0;
      tops.add(top);
    }
    const sorted = [...tops].sort((a, b) => a - b);
    for (let i = 1; i < sorted.length; i++) {
      const d = sorted[i] - sorted[i - 1];
      if (d > 4) { pitch = d; break; }
    }
    for (const w of area.querySelectorAll('[data-calitemid]')) {
      const box = w.closest('[style*="top"]') || w;
      const row = Math.round((parseFloat(box.style.top) || 0) / pitch);
      const more = /^overflowIndicator/.test(w.getAttribute('data-calitemid'))
        ? parseInt((w.textContent.match(/\d+/) || [0])[0], 10) : 1;
      need = Math.max(need, row + more);
    }
    return { need, pitch };
  }

  async function fitAllDay() {
    if (fitting) return;
    const area = allDayArea(), strip = allDayStrip(), heads = dayHeaders();
    if (!area || !strip || !heads.length) return;
    const { need, pitch } = allDayNeed(area);
    const key = heads[0].date + ':' + need;
    if (key === lastFit) return;
    const handle = [...area.querySelectorAll('div')].find(e => getComputedStyle(e).cursor === 'row-resize');
    if (!handle) return;
    const rows = Math.min(need + 1, ALL_DAY_ROWS);
    const h0 = strip.getBoundingClientRect().height;
    const shown = Math.max(Math.round((h0 - 2) / pitch), 0);
    const delta = (rows - shown) * pitch;
    if (Math.abs(delta) < pitch / 2) { lastFit = key; return; }
    if (fitRetry && performance.now() < fitRetry) return;
    fitting = true;
    try {
      const r = handle.getBoundingClientRect();
      const x = r.left + r.width / 2, y0 = r.top + r.height / 2;
      // Mouse events only, every one of them on the handle. Measured
      // 2026-09-17 against four wirings: pointer+mouse with the moves on
      // window, mouse-only on document, and pointer-only on the handle all
      // left the strip where it was; mouse-only on the handle moved it by
      // exactly the distance asked (170 -> 233 for 63px).
      const fire = (type, y) => handle.dispatchEvent(new MouseEvent(type, {
        bubbles: true, cancelable: true, composed: true, button: 0, buttons: 1,
        clientX: x, clientY: y, screenX: x, screenY: y + 100,
      }));
      fire('mousedown', y0);
      await sleep(40);
      for (const y of [y0 + delta / 2, y0 + delta]) { fire('mousemove', y); await sleep(40); }
      fire('mouseup', y0 + delta);
      await sleep(400);
      const h1 = allDayStrip()?.getBoundingClientRect().height ?? h0;
      if (Math.abs(h1 - h0) >= 2) { lastFit = key; fitTries = 0; fitRetry = 0; return; }
      // Early in the load the handle exists before Outlook has wired its
      // drag (measured 2026-09-17: the same sequence that moved the strip
      // from the console did nothing on the first pass after a reload).
      // Try again in a few seconds, a handful of times, then say so.
      if (++fitTries < 5) { fitRetry = performance.now() + 3000; return; }
      lastFit = key; fitTries = 0; fitRetry = 0;
      console.warn('[foresight] all-day strip: the splitter did not move', { from: h0, wanted: h0 + delta });
    } finally { fitting = false; }
  }

  // "Wednesday" becomes "Wed": the short form comes from the column's own
  // date, formatted in the page's language, so it is right in every locale
  // Outlook renders. Only the text node's data changes, never the tree —
  // React keeps its own view of the text and only rewrites it on a
  // re-render, which this loop then catches again. The same walk tags the
  // number and the weekday for the header CSS, and marks today's number.
  let lastDress = 0;
  function dressHeaders() {
    const now = performance.now();
    if (now - lastDress < 1000) return;
    lastDress = now;
    const lang = root.getAttribute('lang') || undefined;
    const today = localDate();
    // The current hour's label in the gutter, for the accent. Matched on
    // the text in both the 24h form ("14") and the locale's own ("2 PM").
    const clock = new Date(), h24 = String(clock.getHours());
    let hLoc = h24;
    try { hLoc = clock.toLocaleTimeString(lang, { hour: 'numeric' }); } catch (_) {}
    for (const t of document.querySelectorAll('[data-owa-24h] > time')) {
      const text = t.textContent.trim();
      t.toggleAttribute('data-owa-now', text === h24 || text === hLoc);
    }
    for (const h of dayHeaders()) {
      let short;
      try { short = new Date(h.date + 'T12:00:00').toLocaleDateString(lang, { weekday: 'short' }); }
      catch (_) { continue; }
      if (!short) continue;
      for (const leaf of h.el.querySelectorAll('*')) {
        if (leaf.children.length || !leaf.firstChild || leaf.firstChild.nodeType !== 3) continue;
        const text = leaf.firstChild.data.trim();
        if (!text) continue;
        if (/^\d+$/.test(text)) {
          leaf.setAttribute('data-owa-daynum', '');
          leaf.toggleAttribute('data-owa-today', h.date === today);
          continue;
        }
        if (!/^\p{L}+\.?$/u.test(text)) continue;   // a word, not a date or a badge
        leaf.setAttribute('data-owa-weekday', '');
        if (text !== short && text.length > short.length) leaf.firstChild.data = short;
      }
    }
  }

  // Nearest in time on the same day, and only then on another day — so a slot
  // at 15:00 with an event at 15:00 lands on that one.
  function nearestEvent(events) {
    const here = labelKey(gridSlot());
    if (!here || !events.length) return events[0];
    let best = events[0], bestDistance = Infinity;
    for (const o of events) {
      const distance = Math.abs(o.key.day - here.day) * 100000
                     + Math.abs(o.key.mins - here.mins);
      if (distance < bestDistance) { bestDistance = distance; best = o; }
    }
    return best;
  }

  const barButtons = () => [...document.querySelectorAll('#omarchy-owa-bar button')]
    .filter(isVisible);

  // Space walks the events on the day you are looking at, nearest first and
  // then in order, wrapping. Tab reaches one event and leaves; this is for
  // reading down a day without losing your place.
  //
  // Free to take: measured on the grid, a bare Space creates nothing, moves
  // nothing and is not otherwise handled. It is left alone while an event is
  // focused, because Space activates a button and opening the event is the
  // more obvious meaning there.
  function cycleDayEvents() {
    const here = labelKey(gridSlot());
    if (!here) return false;
    const sameDay = calendarEvents().filter(o => o.key.day === here.day);
    if (!sameDay.length) return false;
    const ae = document.activeElement;
    const at = sameDay.findIndex(o => o.el === ae || o.el.contains(ae));
    const next = at >= 0 ? sameDay[(at + 1) % sameDay.length] : nearestEvent(sameDay);
    next.el.focus();
    return true;
  }

  function onRegionTab(e) {
    if (e.key !== 'Tab' || e.ctrlKey || e.altKey || e.metaKey) return;
    // The compose runs its own trap, and typing anywhere is never ours.
    if (composeOpen() || root.hasAttribute('data-owa-quickadd')) return;
    if (!root.hasAttribute('data-owa-minimal') || !inCalendar()) return;
    if (isTyping(e.target)) return;

    const ae = document.activeElement;
    const inBar = !!(ae && ae.closest && ae.closest('#omarchy-owa-bar'));
    const inSurface = !!(ae && surface() && surface().contains(ae));
    if (!inBar && !inSurface && ae !== document.body) return;

    const events = calendarEvents();
    const slot = gridSlot();
    const at = events.findIndex(o => o.el === ae || o.el.contains(ae));
    const toBar = () => barButtons()[0]?.focus();
    // Never fall back into the bar. There is not always a selected slot —
    // land somewhere else first and the grid has no selection at all — and
    // falling back to a bar button meant Tab from the bar went to the bar,
    // so it stuck there. Shift+Tab looked fine only because it routes via
    // the nearest event, which does exist.
    const toCalendar = () => {
      if (slot) { slot.focus(); return; }
      if (events.length) { nearestEvent(events).el.focus(); return; }
      // Nothing to focus in the calendar: leave focus alone rather than
      // bouncing it back where it came from.
    };

    e.preventDefault();
    e.stopPropagation();

    // Three stops, and the same three in both directions:
    //
    //     bar  →  slot  →  nearest event  →  bar
    //
    // Stepping through every event on Tab made the ring as long as the day
    // was busy, so going forward from the slot could take ten presses to
    // reach the bar while going back took one. That asymmetry is what made
    // it feel unpredictable. Reaching a *different* event is the arrow keys'
    // job: they move the slot, and Outlook conveniently returns focus to the
    // grid when you press one with an event focused. Arrow to it, Tab to
    // grab it.
    const near = () => (events.length ? nearestEvent(events).el : null);

    if (e.shiftKey) {
      if (inBar) { const t = near(); if (t) t.focus(); else toCalendar(); return; }
      if (at >= 0) { toCalendar(); return; }              // event ← slot
      toBar();                                            // slot ← bar
      return;
    }
    if (inBar || ae === document.body) { toCalendar(); return; }   // bar → slot
    if (at >= 0) { toBar(); return; }                          // event → bar
    const target = near();                                     // slot → event
    if (target) target.focus(); else toBar();
  }

  // With only one stop for the whole bar, its buttons need their own key —
  // the usual toolbar convention.
  function onBarArrows(e) {
    if (!['ArrowLeft', 'ArrowRight'].includes(e.key)) return;
    const ae = document.activeElement;
    if (!ae || !ae.closest || !ae.closest('#omarchy-owa-bar')) return;
    const buttons = barButtons();
    const at = buttons.indexOf(ae);
    if (at < 0) return;
    e.preventDefault();
    const next = e.key === 'ArrowRight' ? at + 1 : at - 1;
    buttons[(next + buttons.length) % buttons.length].focus();
  }

  // Tab should reach the calendar and the bar, and nothing else. Outlook
  // leaves ~60 focusable controls on the page even with its chrome hidden —
  // the suite header, the app rail, the ribbon — because hidden is not the
  // same as untabbable. Those come out of the tab order.
  //
  // What stays is everything inside the calendar surface. Removing events
  // from the tab order took away opening one with Enter and deleting it with
  // Delete, which is a capability the reduction has no business costing.
  const PAGE_KEEP = '[role="main"], [data-app-section="CalendarModule"], '
                  + '#omarchy-owa-bar, #omarchy-owa-toggle, '
                  + '[data-app-section="CalendarSurfaceNavigationToolbar"], '
                  + '#omarchy-owa-pane, [data-owa-pane-host]';
  // Throttled: update() runs on every mutation, and this walks every
  // focusable on the page. Twice a second is far more than enough to catch
  // controls Outlook adds as you navigate.
  let lastRestrict = 0;
  function restrictTabStops(force) {
    if (!root.hasAttribute('data-owa-minimal')) return;
    const now = performance.now();
    if (!force && now - lastRestrict < 500) return;
    lastRestrict = now;
    for (const el of document.querySelectorAll(FOCUSABLE)) {
      if (el.closest('[id^="ModalFocusTrapZone"]')) continue;   // compose owns its own
      if (el.closest(PAGE_KEEP)) { restoreTab(el); continue; }
      if (el.tabIndex < 0) continue;
      el.setAttribute('data-owa-untab', el.getAttribute('tabindex') ?? '');
      el.tabIndex = -1;
    }
  }

  function update() {
    if (queued) return;
    queued = true;
    requestAnimationFrame(() => {
      queued = false;
      if (palette && document.styleSheets.length !== lastSheetCount) paint(false);
      if (quickAddActive && !composeOpen()) {
        quickAddActive = false;
        unstripCompose();
      }
      // The picker mounts into a branch the first strip already hid, so the
      // strip has to run again once it appears: that pass is what clears the
      // hide, puts its fields in the tab order, and nudges it back into
      // view. Without it none of that ever fires, because stripCompose runs
      // exactly once per compose. Guarded on the field's identity, so this
      // is one pass per opening rather than one per frame.
      if (quickAddActive && composeOpen()) {
        const field = q('input[id^="DatePicker"]');
        if (field && nudged !== field) stripCompose();
      }
      if (!root.hasAttribute('data-owa-minimal') || !inCalendar()) return;
      if (splash && q('[role="main"] [data-column-date]')) hideSplash();
      adoptToolbarTheme();
      labelToday();
      syncBar();
      tagDayColumns();
      settleScroll(rescale());
      restrictTabStops();
      keepGridFocused();
      ensureSlot();
      markPast();
      dressHeaders();
      fitAllDay();
    });
  }

  const PANE_KEY = 'omarchy-owa-pane';
  function setPane(on) {
    if (on) root.setAttribute('data-owa-pane', '');
    else root.removeAttribute('data-owa-pane');
    try { localStorage.setItem(PANE_KEY, on ? '1' : '0'); } catch (_) {}
    update();
  }

  function setEnabled(on) {
    if (on) root.setAttribute('data-owa-minimal', '');
    else root.removeAttribute('data-owa-minimal');
    try { localStorage.setItem(STORE_KEY, on ? '1' : '0'); } catch (_) {}
    if (on) update();
  }

  // Today is Outlook's button; its tooltip gets the key like ours. React
  // rewrites the title on re-render, so this is re-applied by the loop.
  function labelToday() {
    const t = navButton(0);
    if (t && t.title && !t.title.includes('(t)')) t.title = t.title.replace(/\s*$/, '') + ' (t)';
  }

  // `?` shows the keys. A dialog in the palette's colours; `?`, Escape or a
